def ensure_visual_entries() -> None:
    """
    Check if visual self-images exist in vault, add if missing.
    Call once at startup.
    """
    try:
        import relationship_vault as rv

        current_count = rv.count()
        self_images = [m for m in rv.get_recent(100) if m.get("category") == "self-image"]

        if len(self_images) >= len(VISUAL_ENTRIES):
            logger.info(f"[visual_self] ✓ visual entries already present ({len(self_images)})")
            return

        logger.info(f"[visual_self] initializing visual self-images ({len(VISUAL_ENTRIES)} entries)...")
        for entry in VISUAL_ENTRIES:
            try:
                entry_id = rv.add_memory(**entry, source="visual_self")
                logger.debug(f"[visual_self] added: {entry['title']} (id: {entry_id})")
            except Exception as e:
                logger.warning(f"[visual_self] failed to add {entry['title']}: {e}")

        total = rv.count()
        logger.info(f"[visual_self] ✓ initialization complete — vault now has {total} total entries")

    except Exception as e:
        logger.warning(f"[visual_self] initialization failed: {e}")
